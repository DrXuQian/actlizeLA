"""Relocatable, file-only discovery of an identity-bound serving wheel.

This is integrity checking, not a replacement for artifact signing. The manifest
binds every package resource (including Python bindings); wheel.json seals its
bytes. Neither discovery nor top-level import loads a DSO or probes a device.
"""

import hashlib
import json
from pathlib import Path, PurePosixPath

from ._serving_contract import (
    ABI_VERSION,
    EXPORTS,
    HEADERS,
    REQUIRED_BINDINGS,
    STRUCT_NAMES,
    TARGET_IDS,
    TARGET_PREPARED_EXPORTS,
)
from ._version import __version__


class LibraryError(RuntimeError):
    """The installed serving artifact is absent, incompatible or incomplete."""


def _sha(path):
    h = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def _resource(root, name):
    if not isinstance(name, str) or not name or "\\" in name:
        raise LibraryError(f"invalid package resource: {name!r}")
    path = PurePosixPath(name)
    if (
        path.is_absolute()
        or any(p in (".", "..") for p in path.parts)
        or str(path) != name
    ):
        raise LibraryError(f"non-relative package resource: {name!r}")
    result = root / name
    # No symlink escape or dependence on another installation, even inside a
    # nominally well-formed relative path.
    if any(
        (root / Path(*path.parts[:i])).is_symlink()
        for i in range(1, len(path.parts) + 1)
    ):
        raise LibraryError(f"symlink package resource: {name}")
    if not result.is_file() or not result.resolve().is_relative_to(root):
        raise LibraryError(f"missing package resource: {name}")
    return result


def _json(path):
    def unique(pairs):
        result = {}
        for key, value in pairs:
            if key in result:
                raise LibraryError(f"duplicate manifest key: {key}")
            result[key] = value
        return result

    try:
        return json.loads(path.read_text(encoding="utf-8"), object_pairs_hook=unique)
    except (OSError, ValueError) as exc:
        raise LibraryError(f"invalid serving metadata: {path.name}") from exc


def _inspect(root, target):
    try:
        seal_path = _resource(root, "_native/wheel.json")
    except LibraryError as exc:
        raise LibraryError(
            "complete precompiled actlize-la serving wheel not installed; "
            "a source/host-only package is not a native backend"
        ) from exc
    seal = _json(seal_path)
    manifest_path = _resource(root, "_native/manifest.json")
    digest = _sha(manifest_path)
    if seal.get("schema") != 1 or seal.get("manifest_sha256") != digest:
        raise LibraryError("serving manifest identity mismatch")
    manifest = _json(manifest_path)
    if manifest.get("schema") != 1 or manifest.get("version") != __version__:
        raise LibraryError("serving manifest schema/Python version mismatch")
    targets = manifest["targets"]
    if not targets or not set(targets) <= TARGET_IDS.keys():
        raise LibraryError("unsupported serving targets in manifest")
    selected = manifest.get("default_target") if target is None else target
    if not isinstance(selected, str) or selected not in targets:
        raise LibraryError(
            f"target {selected!r} unavailable or default ambiguous; "
            f"supported={sorted(targets)}; no fallback"
        )
    files = manifest["resources"]
    if not set(REQUIRED_BINDINGS) <= files.keys():
        raise LibraryError("serving manifest omits required Python bindings")
    # Extra production files can shadow an admitted module, so they are not
    # silently ignored. Installation-generated bytecode is the sole exception.
    actual = {
        p.relative_to(root).as_posix()
        for p in root.rglob("*")
        if p.is_file() and "__pycache__" not in p.parts and p.suffix != ".pyc"
    }
    actual -= {"_native/wheel.json", "_native/manifest.json"}
    if actual != set(files):
        raise LibraryError(
            f"package resource inventory changed: "
            f"missing={sorted(set(files) - actual)}, extra={sorted(actual - set(files))}"
        )
    for name, expected in files.items():
        if _sha(_resource(root, name)) != expected:
            raise LibraryError(f"package resource hash mismatch: {name}")
    for name, record in targets.items():
        if set(record.get("prepared_exports", ())) != set(TARGET_PREPARED_EXPORTS[name]):
            raise LibraryError(f"manifest omits retained prepared capability for {name}")
        abi = record["abi"]
        if (
            abi["version"] != ABI_VERSION
            or abi["target"] != TARGET_IDS[name]
            or set(abi["exports"]) != set(EXPORTS)
            or set(abi["struct_sizes"]) != set(STRUCT_NAMES)
            or any(type(n) is not int or n <= 0 for n in abi["struct_sizes"].values())
        ):
            raise LibraryError(f"native/Python ABI identity mismatch for {name}")
        for field in ("library", "native_graph_example"):
            if record[field] not in files:
                raise LibraryError(f"unbound {field} for {name}")
        if not all(f"_native/{name}/{header}" in files for header in HEADERS):
            raise LibraryError(f"missing serving ABI headers for {name}")
        if not record["compatibility"].get("compiler_version"):
            raise LibraryError(f"missing actual toolchain identity for {name}")
    record = targets[selected]
    return dict(
        version=manifest["version"],
        source_revision=manifest["source_revision"],
        source_dirty=manifest["source_dirty"],
        supported_targets=sorted(targets),
        target=selected,
        library_path=str(_resource(root, record["library"])),
        manifest_path=str(manifest_path),
        manifest_sha256=digest,
        native_graph_example=str(_resource(root, record["native_graph_example"])),
        compatibility=record["compatibility"],
        abi=record["abi"],
        prepared_exports=record.get("prepared_exports", []),
        source_identity=manifest["source_identity"],
    )


def get_library_info(target=None):
    """Return validated JSON-serializable wheel identity, without device access."""
    try:
        return _inspect(Path(__file__).resolve().parent, target)
    except (KeyError, TypeError, AttributeError, OSError) as exc:
        raise LibraryError(f"incomplete or malformed serving artifact: {exc}") from exc


def get_library_path(target=None):
    """Return the absolute pathlib.Path of the verified packaged serving DSO."""
    return Path(get_library_info(target)["library_path"])
